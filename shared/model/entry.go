// Package model holds the types shared by the server and the desktop app.
package model

import (
	"encoding/json"
	"regexp"
	"sort"
	"strings"
	"time"
)

// EmptyBody is the ProseMirror JSON of an empty document.
const EmptyBody = `{"type":"doc","content":[]}`

// EmptyMeta is the meta of an entry with no icon, properties or schema.
const EmptyMeta = `{}`

// Kinds of entry. A database record is a page whose parent is a database.
const (
	KindPage     = "page"
	KindDatabase = "database"
)

type Entry struct {
	ID        string          `json:"id"`         // UUID v7, generated by the client
	EntryDate *string         `json:"entry_date"` // "2026-10-05" or null for free notes
	Kind      string          `json:"kind"`       // "page" | "database"
	ParentID  *string         `json:"parent_id"`  // parent page, or the database of a record
	Title     string          `json:"title"`
	Body      json.RawMessage `json:"body"`    // ProseMirror JSON document
	Meta      json.RawMessage `json:"meta"`    // {"icon", "props"} or, for a database, {"icon", "schema"}
	Version   int             `json:"version"` // 1 on create, +1 every write
	ServerSeq int64           `json:"server_seq"`
	CreatedAt time.Time       `json:"created_at"`
	UpdatedAt time.Time       `json:"updated_at"`
	DeletedAt *time.Time      `json:"deleted_at"` // non-nil = tombstone
}

// Deleted reports whether the entry is a tombstone.
func (e Entry) Deleted() bool { return e.DeletedAt != nil }

var (
	uuidRE   = regexp.MustCompile(`^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$`)
	dateRE   = regexp.MustCompile(`^\d{4}-\d{2}-\d{2}`)
	optionRE = regexp.MustCompile(`^opt_[A-Za-z0-9]+$`)
)

// IsUUID reports whether s is a UUID in its 36-character form.
func IsUUID(s string) bool { return uuidRE.MatchString(s) }

type metaProps struct {
	Props map[string]json.RawMessage `json:"props"`
}

// MetaLinks returns the entry ids a record's relation properties point to:
// every UUID inside an array-valued property.
func MetaLinks(meta json.RawMessage) []string {
	var m metaProps
	if json.Unmarshal(meta, &m) != nil {
		return nil
	}
	seen := map[string]bool{}
	for _, raw := range m.Props {
		var list []string
		if json.Unmarshal(raw, &list) != nil {
			continue
		}
		for _, s := range list {
			if IsUUID(s) {
				seen[strings.ToLower(s)] = true
			}
		}
	}
	return sortedKeys(seen)
}

// MetaText returns the free-text property values (text and URL properties),
// so search finds them. Option ids, dates and relation ids are skipped.
func MetaText(meta json.RawMessage) string {
	var m metaProps
	if json.Unmarshal(meta, &m) != nil {
		return ""
	}
	keys := make([]string, 0, len(m.Props))
	for k := range m.Props {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var parts []string
	for _, k := range keys {
		var s string
		if json.Unmarshal(m.Props[k], &s) != nil || s == "" {
			continue
		}
		if IsUUID(s) || optionRE.MatchString(s) || dateRE.MatchString(s) {
			continue
		}
		parts = append(parts, s)
	}
	return strings.Join(parts, "\n")
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
